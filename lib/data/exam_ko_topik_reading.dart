McqQuestion _q(String id, String en, List<String> options) =>
    McqQuestion(question: {'id': id, 'en': en}, options: options, answer: 0);

ReadingPassage _p(
  String id,
  String titleId,
  String titleEn,
  String text,
  List<McqQuestion> questions,
) => ReadingPassage(
  id: id,
  title: {'id': titleId, 'en': titleEn},
  text: text,
  questions: questions,
);

/// 무엇에 대한 내용입니까? (soal 31–33)
McqQuestion _topic(String text, List<String> o) => _q(
  'Teks ini tentang apa? (무엇에 대한 내용입니까?)\n$text',
  'What is this about? (무엇에 대한 내용입니까?)\n$text',
  o,
);

/// ( )에 들어갈 가장 알맞은 것 (soal 34–39)
McqQuestion _blank(String text, List<String> o) => _q(
  'Pilih yang paling tepat untuk ( ):\n$text',
  'Choose the best fit for ( ):\n$text',
  o,
);

/// 다음의 내용과 같은 것 (soal 43–45)
McqQuestion _match(String text, List<String> o) => _q(
  'Pilih kalimat yang sesuai dengan isi teks:\n$text',
  'Choose the sentence that matches the text:\n$text',
  o,
);

/// 중심 생각 (soal 46–48)
McqQuestion _main(String text, List<String> o) => _q(
  'Pilih gagasan utama teks ini (중심 생각):\n$text',
  'Choose the main idea of this text (중심 생각):\n$text',
  o,
);

/// 순서대로 맞게 나열한 것 (soal 57–58)
McqQuestion _order(String text, List<String> o) => _q(
  'Pilih urutan kalimat yang paling tepat:\n$text',
  'Choose the correct order of the sentences:\n$text',
  o,
);

